/**
 * One shell segment split into words, with quotes removed.
 *
 * This is the word reader the gate and the heredoc normalizer share. It is not
 * a full shell expansion: `$VAR`, a glob, and a substitution stay as text, and
 * the gate's own runtime-shape check decides what to do with them.
 */

/** Split one segment into shell words, removing quotes. */
export function shellWords(segment: string): string[] {
	const words: string[] = [];
	let word = "";
	let inWord = false;
	let quote: "'" | '"' | null = null;
	for (let i = 0; i < segment.length; i++) {
		const ch = segment[i];
		if (quote === "'") {
			if (ch === "'") quote = null;
			else word += ch;
		} else if (quote === '"') {
			if (ch === '"') quote = null;
			else if (ch === "\\" && i + 1 < segment.length) word += segment[++i];
			else word += ch;
		} else if (ch === "'" || ch === '"') {
			quote = ch;
			inWord = true;
		} else if (ch === "\\" && i + 1 < segment.length) {
			word += segment[++i];
			inWord = true;
		} else if (/\s/.test(ch)) {
			if (inWord) words.push(word);
			word = "";
			inWord = false;
		} else {
			word += ch;
			inWord = true;
		}
	}
	if (inWord) words.push(word);
	return words;
}
