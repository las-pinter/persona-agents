/**
 * The pi permission rule table. Data only.
 *
 * Seventy-seven rows carry three class groups:
 *   - 21 global rows  (all three classes),
 *   - 14 reader rows,
 *   - 18 worker rows,
 *   - 24 orchestrator rows.
 *
 * A row is a name, a tool, a verdict, the classes that get it, and a geometry of
 * plain words. A row may also carry `roles`, which narrows its class scope to
 * the professions it names. The geometry is `verb`, `sub`, `flags`, `zone`,
 * `probe`, `arg`, and `span`. No row carries a regex, a pattern string, or a
 * compiled value. `permission-table.ts` builds the pattern, the wrapper column,
 * the git option column, the option tail, the path zone, the probe shape, and
 * the exception tail. Every option ladder lives in that module as a named
 * constant, so a row never spells one.
 *
 * A rule that two classes share is one row per class with the same id, the same
 * verdict, and the same geometry. The compiler refuses a shared id that
 * disagrees with itself.
 *
 * Row groups, by class:
 *   global 21, reader 14, worker 18, orchestrator 24, total 77.
 * Rows a class resolves to: reader 35, worker 39, orchestrator 45.
 *
 * Fences. A deny row that names an option requires that option, so the bare
 * command stays untouched. `find` denies on `-exec`, `-fls`, and the `-fprint`
 * forms. `git tag` denies a short or long delete form at every abbreviation.
 * `rg` denies the preprocessor and decompressor options, and `date` denies `-s`.
 * The git diff family denies `--output`, `--ext-diff`, `--textconv`, and
 * `--filters` at every unique abbreviation. The family names `annotate`, so the
 * verb a read row allows is fenced too. A stream write (`>` and `tee`) denies
 * for every class, because it leaves the write zone. `git fetch` denies a
 * colon-shaped refspec for a reader or a worker, and a plain `git fetch` asks
 * for a worker only. `dd` denies only with a device write, so a plain copy runs.
 *
 * `git branch` is one read row with a listing-only tail. A branch write form
 * falls outside the tail and reaches deny-by-default, so no class can create,
 * move, or delete a branch through the read row.
 *
 * Commands the shared read rows omit, and deny-by-default therefore blocks:
 *   - `xxd`, `printf`, `sha256sum`, `mktemp`, `test`, `mdl`, and a
 *     `.venv/bin/<tool>` wrapper; `printf`, `sha256sum`, `test`, and `mdl` are
 *     recorded narrowings: they reach a worker in the legacy frontmatter only.
 *     The three write-shaped read verbs `mkdir`, `sort`, and `uniq` ride the
 *     orchestrator's own journal row only;
 *   - `git remote`, `git reflog`, `git config`, `git grep`, `git cat-file`,
 *     `git ls-remote`, `git fetch`, `git hash-object`, and `git fsck`.
 * A build or test runner is not a read-only probe: the reader toolchain row
 * names version and metadata probes only, so no reader class runs a test.
 */

